package com.idol.store.data

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import okhttp3.OkHttpClient
import okhttp3.Request

@Serializable
data class SecurityReport(
    val results: List<SecurityResult> = emptyList(),
)

@Serializable
data class SecurityResult(
    val id: String,
    val status: String,
    val scannedAt: String? = null,
    val release: SecurityRelease? = null,
    val source: SecuritySource? = null,
    val assets: List<SecurityAsset> = emptyList(),
)

@Serializable
data class SecurityRelease(
    val tag: String? = null,
)

@Serializable
data class SecuritySource(
    val status: String? = null,
    val dependencyAudit: SecurityDependencyAudit? = null,
)

@Serializable
data class SecurityDependencyAudit(
    val status: String? = null,
)

@Serializable
data class SecurityAsset(
    val name: String,
    val sha256: String? = null,
    val status: String? = null,
)

/**
 * Reads the public scan report generated by the catalog repository's GitHub Actions workflow.
 * A missing or unavailable report is treated as "not yet scanned", never as a clean result.
 */
object SecurityRepository {
    private const val REPORT_URL =
        "https://raw.githubusercontent.com/Alvandcode/idol-store-catalog/main/security-results.json"

    private val client = OkHttpClient()
    private val json = Json { ignoreUnknownKeys = true }

    suspend fun load(): List<SecurityResult> = withContext(Dispatchers.IO) {
        val request = Request.Builder()
            .url(REPORT_URL)
            .header("Cache-Control", "no-cache")
            .build()
        client.newCall(request).execute().use { response ->
            if (!response.isSuccessful) return@withContext emptyList()
            val body = response.body?.string().orEmpty()
            if (body.isBlank()) return@withContext emptyList()
            json.decodeFromString<SecurityReport>(body).results
        }
    }
}
